  let currentLang = localStorage.getItem('cdna_admin_lang') || 'zh';

  function getLang() {
    return currentLang;
  }

  function setLang(lang) {
    currentLang = lang === 'en' ? 'en' : 'zh';
    localStorage.setItem('cdna_admin_lang', currentLang);
    applyI18n();

    // Trigger full re-render of current active tab & shell so all dynamic text updates!
    if (window.AdminApp && typeof window.AdminApp.onLanguageChange === 'function') {
      window.AdminApp.onLanguageChange();
    }
  }

  function toggleLang() {
    setLang(currentLang === 'zh' ? 'en' : 'zh');
  }

  function t(key, params = {}, fallback = '') {
    const dict = DICT[currentLang] || DICT.zh;
    let text = dict[key] || fallback || key;
    if (typeof params === 'object' && params !== null) {
      Object.keys(params).forEach(p => {
        text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
      });
    }
    return text;
  }

  function applyI18n() {
    const dict = DICT[currentLang] || DICT.zh;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.innerText = dict[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) el.setAttribute('placeholder', dict[key]);
    });

    const label = document.getElementById('lang-label');
    if (label) label.innerText = currentLang === 'zh' ? '繁中 / EN' : 'EN / 繁中';
  }

  return {
    getLang,
    setLang,
    toggleLang,
    t,
    applyI18n
  };
